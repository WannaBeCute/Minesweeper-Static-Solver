def 转换为矩阵(data: str, 映射字符: str = ''):
    mat_str = data.strip().replace(' ', '')
    if 映射字符:    #不为空时则进行映射
        if len(set([i for i in 映射字符])) != 10:
            return print("映射字符错误！请仔细检查！")
        else:
            映射表, 目标字符 = {}, '?012345678'
            for i in range(9):
                映射表[映射字符[i]] = 目标字符[i]
            mapping = str.maketrans(映射表)
            mat_str = mat_str.translate(mapping)  # 翻译为可供程序识别的矩阵
    mat = [[char for char in lst] for lst in mat_str.split('\n')]
    return mat

